import assert from 'node:assert/strict'
import { readFile } from 'node:fs/promises'

const toolbar = await readFile(new URL('../../src/components/generate/toolbars/ImageToolbar.vue', import.meta.url), 'utf8')
const addHandle = await readFile(new URL('../../src/components/canvas/CanvasNodeAddHandle.vue', import.meta.url), 'utf8')
const imageNode = await readFile(new URL('../../src/views/workflow/components/nodes/ImageNode.vue', import.meta.url), 'utf8')
const videoNode = await readFile(new URL('../../src/views/workflow/components/nodes/VideoNode.vue', import.meta.url), 'utf8')
const generator = await readFile(new URL('../../src/components/generate/ContentGenerator.vue', import.meta.url), 'utf8')
const roleEdge = await readFile(new URL('../../src/views/workflow/components/edges/ImageRoleEdge.vue', import.meta.url), 'utf8')
const runtime = await readFile(new URL('../../src/views/workflow/composables/useAgentRuntime.ts', import.meta.url), 'utf8')

assert.match(toolbar, /currentImageModel/, 'image sizes must follow the selected backend model')
assert.match(toolbar, /currentResolution/, 'image resolution must be selected independently from aspect ratio')
assert.match(toolbar, /SEEDREAM_SIZE_OPTIONS/, 'all supported custom aspect ratios must be offered')
assert.match(addHandle, /defineEmits/, 'the add handle must expose a click action')
assert.match(imageNode, /createAdjacentImageNode/, 'image add handles must create connected adjacent nodes')
assert.match(videoNode, /imageRole: 'first_frame'/, 'image-to-video must use the first-frame input role')
assert.match(videoNode, /:external-reference-images="upstreamReferenceUrls"/, 'linked image previews must reach the video editor')
assert.match(videoNode, /loadMediaPreview\(source\)/, 'linked image previews must use authenticated media loading')
assert.match(generator, /currentType\.value === 'video'/, 'the video editor must render linked image previews')
assert.match(generator, /referenceImages: \[videoFirstFrameImage\.value, videoLastFrameImage\.value\]/, 'video frame uploads must be included in submissions')
assert.match(generator, /@click="swapVideoFrames"/, 'the first/last frame swap control must be functional')
assert.match(videoNode, /@video-frame-change="handleVideoFrameChange"/, 'video frame uploads must update canvas inputs')
assert.match(videoNode, /await pendingVideoFrameChange/, 'generation must wait for frame uploads')
assert.match(roleEdge, /key: 'first_frame'/, 'video edges must persist the backend first-frame role')
assert.match(roleEdge, /key: 'last_frame'/, 'video edges must persist the backend last-frame role')
assert.match(runtime, /first_last_frame_to_video/, 'first and last frame inputs must select the matching backend mode')
assert.match(runtime, /current\?\.media_ref/, 'editing an existing image must use its current media as a reference')

console.log('workflow image controls: ok')
